//go:build windows

package tray

// Tray icons, as Windows .ico bytes.
//
// Two icons, not one: an employee glancing at the tray must be able to tell "recording" from
// "not recording" without hovering. A single icon with a tooltip would technically satisfy
// "visible" while telling them nothing at a glance.
//
// Embedded as literals rather than loaded from disk, deliberately. The agent ships as a single
// static binary (CGO_ENABLED=0, one .exe); an icon read from a file beside it is a file that can
// be deleted or replaced, and a missing icon would mean an invisible tray — which the design
// treats as fatal. Embedding removes that failure mode entirely.
//
// Each is a minimal 16x16 32-bit BMP-in-ICO: a filled circle, green for recording and grey for
// paused. Generated by internal/tray/gen/main.go; regenerate rather than hand-editing.

var (
	// iconRecording is shown whenever activity is being captured.
	iconRecording = buildIcon(0x2E, 0xA0, 0x43) // green
	// iconPaused is shown when the privacy filter is suppressing capture, when the device is not
	// enrolled, and when the notice has not yet been acknowledged.
	iconPaused = buildIcon(0x8A, 0x8A, 0x8A) // grey
)

// buildIcon assembles a 16x16 ICO with a filled circle in the given colour.
//
// Written as code rather than a byte blob so the two icons cannot drift apart in shape, and so the
// colours are legible in review — a hardcoded ICO is unreviewable, and an unreviewable indicator
// is one nobody notices has broken.
func buildIcon(r, g, b byte) []byte {
	const size = 16

	// ICONDIR (6 bytes) + ICONDIRENTRY (16 bytes) + BITMAPINFOHEADER (40) + pixels + mask.
	pixels := make([]byte, 0, size*size*4)

	// Bottom-up, as BMP requires.
	for y := size - 1; y >= 0; y-- {
		for x := 0; x < size; x++ {
			// Distance from the centre of a 16x16 grid, in half-pixel units to avoid a
			// lopsided circle.
			dx := float64(x)*2 - (size - 1)
			dy := float64(y)*2 - (size - 1)
			inside := dx*dx+dy*dy <= float64((size-2)*(size-2))

			if inside {
				// BGRA, pre-multiplied alpha not required for a fully opaque pixel.
				pixels = append(pixels, b, g, r, 0xFF)
			} else {
				pixels = append(pixels, 0x00, 0x00, 0x00, 0x00)
			}
		}
	}

	// The AND mask is unused for a 32-bit icon with an alpha channel, but the format still
	// requires the rows to be present and padded to 4 bytes.
	maskRowBytes := ((size + 31) / 32) * 4
	mask := make([]byte, maskRowBytes*size)

	imageSize := 40 + len(pixels) + len(mask)

	icon := make([]byte, 0, 22+imageSize)

	// ICONDIR
	icon = append(icon, 0x00, 0x00) // reserved
	icon = append(icon, 0x01, 0x00) // type 1 = icon
	icon = append(icon, 0x01, 0x00) // one image

	// ICONDIRENTRY
	icon = append(icon, size, size) // width, height
	icon = append(icon, 0x00)       // palette colours (0 = 256+)
	icon = append(icon, 0x00)       // reserved
	icon = append(icon, 0x01, 0x00) // colour planes
	icon = append(icon, 0x20, 0x00) // 32 bits per pixel
	icon = appendUint32(icon, uint32(imageSize))
	icon = appendUint32(icon, 22) // offset to the image data

	// BITMAPINFOHEADER. Height is doubled because the format counts the colour rows and the
	// mask rows together.
	icon = appendUint32(icon, 40)
	icon = appendUint32(icon, size)
	icon = appendUint32(icon, size*2)
	icon = append(icon, 0x01, 0x00) // planes
	icon = append(icon, 0x20, 0x00) // bit count
	icon = appendUint32(icon, 0)    // BI_RGB
	icon = appendUint32(icon, uint32(len(pixels)+len(mask)))
	icon = appendUint32(icon, 0) // horizontal resolution
	icon = appendUint32(icon, 0) // vertical resolution
	icon = appendUint32(icon, 0) // palette entries used
	icon = appendUint32(icon, 0) // important colours

	icon = append(icon, pixels...)
	icon = append(icon, mask...)

	return icon
}

func appendUint32(dst []byte, value uint32) []byte {
	return append(dst, byte(value), byte(value>>8), byte(value>>16), byte(value>>24))
}
