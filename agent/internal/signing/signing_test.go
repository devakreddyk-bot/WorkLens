// contract mirrors contracts/signature-vectors.json.
//
// That file is the pinned agreement with the TypeScript verifier in
// backend/src/shared/signature.ts. The two implementations share no code, so these vectors
// are the only thing keeping them in agreement — and the failure they prevent is a fleet that
// authenticates against nothing, reporting "signature mismatch" with no clue which side is
// wrong. backend/test/shared/signatureVectors.test.ts reads the same file.
type contract struct {
	Algorithm struct {
		CanonicalRequest       string `json:"canonicalRequest"`
		TimestampWindowSeconds int    `json:"timestampWindowSeconds"`
		PathHandling           string `json:"pathHandling"`
	} `json:"algorithm"`

	DeviceSecretDerivation struct {
		RootKeyBase64  string `json:"rootKeyBase64"`
		OrgID          string `json:"orgId"`
		DeviceID       string `json:"deviceId"`
		KeyVersion     int    `json:"keyVersion"`
		ExpectedSecret string `json:"expectedSecret"`
	} `json:"deviceSecretDerivation"`

	Signing struct {
		DeviceSecret string `json:"deviceSecret"`
		Cases        []struct {
			Name                     string `json:"name"`
			Why                      string `json:"why"`
			Method                   string `json:"method"`
			Path                     string `json:"path"`
			Timestamp                int64  `json:"timestamp"`
			Nonce                    string `json:"nonce"`
			Body                     string `json:"body"`
			ExpectedCanonicalRequest string `json:"expectedCanonicalRequest"`
			ExpectedSignature        string `json:"expectedSignature"`
		} `json:"cases"`
	} `json:"signing"`
}

func loadContract(t *testing.T) contract {
	t.Helper()

	// Up from agent/internal/signing to the repository root.
	path := filepath.Join("..", "..", "..", "contracts", "signature-vectors.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("could not read the signing contract at %s: %v\n"+
			"It is generated by `npm run gen:vectors` in backend/ and must be committed.", path, err)
	}

	var c contract
	if err := json.Unmarshal(raw, &c); err != nil {
		t.Fatalf("signing contract is not valid JSON: %v", err)
	}

	// A contract that silently emptied would make every assertion below vacuously pass.
	if len(c.Signing.Cases) < 8 {
		t.Fatalf("expected at least 8 signing vectors, found %d — has the contract been truncated?",
			len(c.Signing.Cases))
	}
	return c
}

// TestContractVectors is the load-bearing test in this package.
func TestContractVectors(t *testing.T) {
	c := loadContract(t)

	for _, tc := range c.Signing.Cases {
		t.Run(tc.Name, func(t *testing.T) {
			req := Request{
				Method:    tc.Method,
				Path:      tc.Path,
				Timestamp: tc.Timestamp,
				Nonce:     tc.Nonce,
				Body:      []byte(tc.Body),
			}

			if got := CanonicalRequest(req); got != tc.ExpectedCanonicalRequest {
				t.Errorf("canonical request does not match the contract (%s)\n got: %q\nwant: %q",
					tc.Why, got, tc.ExpectedCanonicalRequest)
			}

			if got := Sign(c.Signing.DeviceSecret, req); got != tc.ExpectedSignature {
				t.Errorf("signature does not match the contract (%s)\n got: %s\nwant: %s",
					tc.Why, got, tc.ExpectedSignature)
			}
		})
	}
}

// TestDeviceSecretDerivation checks the agent agrees with the server about what a device
// secret *is*, not just how a request is signed.
//
// The agent receives its secret at enrolment and never derives one, so this is a contract
// check rather than production code being exercised: if the server's derivation changed, every
// existing device's stored secret would stop working, and this test says so.
func TestDeviceSecretDerivation(t *testing.T) {
	c := loadContract(t)
	d := c.DeviceSecretDerivation

	rootKey, err := base64.StdEncoding.DecodeString(d.RootKeyBase64)
	if err != nil {
		t.Fatalf("root key in the contract is not valid base64: %v", err)
	}

	message := "v" + itoa(d.KeyVersion) + ":" + d.OrgID + ":" + d.DeviceID
	mac := hmac.New(sha256.New, rootKey)
	_, _ = mac.Write([]byte(message))
	got := base64.RawURLEncoding.EncodeToString(mac.Sum(nil))

	if got != d.ExpectedSecret {
		t.Errorf("derived device secret does not match the contract\n got: %s\nwant: %s", got, d.ExpectedSecret)
	}
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var digits []byte
	for n > 0 {
		digits = append([]byte{byte('0' + n%10)}, digits...)
		n /= 10
	}
	return string(digits)
}

// TestCanonicalRequestShape pins the properties the vectors exist to protect, stated as
// assertions rather than left implicit in the fixture.
func TestCanonicalRequestShape(t *testing.T) {
	base := Request{
		Method:    "POST",
		Path:      "/v1/device/events",
		Timestamp: 1760000000,
		Nonce:     "0123456789abcdef0123456789abcdef",
		Body:      []byte(`{"window_title":"Quarterly board pack"}`),
	}

	canonical := CanonicalRequest(base)
	lines := strings.Split(canonical, "\n")

	if len(lines) != 5 {
		t.Fatalf("canonical request must have exactly 5 lines, got %d: %q", len(lines), canonical)
	}
	if lines[0] != "POST" {
		t.Errorf("line 0 must be the upper-cased method, got %q", lines[0])
	}
	if lines[1] != base.Path {
		t.Errorf("line 1 must be the path verbatim, got %q", lines[1])
	}
	if lines[2] != "1760000000" {
		t.Errorf("line 2 must be the unix timestamp, got %q", lines[2])
	}
	if lines[3] != base.Nonce {
		t.Errorf("line 3 must be the nonce, got %q", lines[3])
	}
	if len(lines[4]) != 2*sha256.Size {
		t.Errorf("line 4 must be a sha256 hex digest, got %q", lines[4])
	}

	// The body must never appear in the clear: the canonical string is loggable, a request
	// body full of window titles is not.
	if strings.Contains(canonical, "Quarterly board pack") {
		t.Error("the body leaked into the canonical request; it must appear only as a hash")
	}
}

func TestMethodIsUpperCased(t *testing.T) {
	// A caller passing a lower-case verb must still produce a verifiable signature, because
	// the server upper-cases too.
	lower := Request{Method: "post", Path: "/x", Timestamp: 1, Nonce: "a", Body: nil}
	upper := lower
	upper.Method = "POST"

	if CanonicalRequest(lower) != CanonicalRequest(upper) {
		t.Error("method must be upper-cased before signing")
	}
}

func TestPathIsNotNormalised(t *testing.T) {
	// If this ever starts passing, someone added path normalisation — and the TypeScript
	// verifier must be changed identically or every request with a trailing slash fails.
	withSlash := Request{Method: "GET", Path: "/v1/device/config/", Timestamp: 1, Nonce: "a"}
	without := withSlash
	without.Path = "/v1/device/config"

	if CanonicalRequest(withSlash) == CanonicalRequest(without) {
		t.Error("paths differing by a trailing slash must not canonicalise to the same string")
	}
}

func TestEmptyBodyHashesTheEmptyString(t *testing.T) {
	// nil and empty must be identical: the agent uses nil for a GET and []byte{} in places,
	// and the server always hashes the empty string. A difference here would break config
	// polling only, which is a confusing way to discover it.
	withNil := Request{Method: "GET", Path: "/x", Timestamp: 1, Nonce: "a", Body: nil}
	withEmpty := withNil
	withEmpty.Body = []byte{}

	if CanonicalRequest(withNil) != CanonicalRequest(withEmpty) {
		t.Error("a nil body and an empty body must produce the same canonical request")
	}

	emptyHash := sha256.Sum256(nil)
	if !strings.HasSuffix(CanonicalRequest(withNil), hex.EncodeToString(emptyHash[:])) {
		t.Error("an empty body must hash to sha256 of the empty string")
	}
}

func TestBodyIsTamperEvident(t *testing.T) {
	req := Request{Method: "POST", Path: "/v1/device/events", Timestamp: 1, Nonce: "a", Body: []byte(`{"a":1}`)}
	original := Sign("secret", req)

	tampered := req
	tampered.Body = []byte(`{"a":2}`)

	if Sign("secret", tampered) == original {
		t.Error("changing the body must change the signature")
	}
}

func TestSignatureChangesWithEveryField(t *testing.T) {
	base := Request{
		Method:    "POST",
		Path:      "/v1/device/events",
		Timestamp: 1760000000,
		Nonce:     "0123456789abcdef0123456789abcdef",
		Body:      []byte(`{}`),
	}
	baseline := Sign("secret", base)

	mutations := map[string]Request{
		"method":    func() Request { r := base; r.Method = "PUT"; return r }(),
		"path":      func() Request { r := base; r.Path = "/v1/device/config"; return r }(),
		"timestamp": func() Request { r := base; r.Timestamp++; return r }(),
		"nonce":     func() Request { r := base; r.Nonce = strings.Repeat("f", 32); return r }(),
		"body":      func() Request { r := base; r.Body = []byte(`{"x":1}`); return r }(),
	}

	for name, mutated := range mutations {
		if Sign("secret", mutated) == baseline {
			t.Errorf("changing %s must change the signature", name)
		}
	}

	if Sign("a-different-secret", base) == baseline {
		t.Error("changing the secret must change the signature")
	}
}

func TestGenerateNonce(t *testing.T) {
	seen := make(map[string]struct{}, 2000)
	for i := 0; i < 2000; i++ {
		nonce, err := GenerateNonce()
		if err != nil {
			t.Fatalf("GenerateNonce failed: %v", err)
		}
		if err := ValidateNonce(nonce); err != nil {
			t.Fatalf("generated a nonce the server would reject: %v", err)
		}
		if _, dup := seen[nonce]; dup {
			// A repeated nonce would look exactly like a replay attempt to the server and
			// drop a legitimate batch.
			t.Fatalf("GenerateNonce repeated a value after %d draws", i)
		}
		seen[nonce] = struct{}{}
	}
}

func TestHeaders(t *testing.T) {
	creds := Credentials{DeviceID: "9a594a02-afe7-4537-b57a-f771875c3c87", Secret: "s3cr3t"}
	now := time.Unix(1760000000, 0)
	body := []byte(`{"events":[]}`)

	headers, err := Headers(creds, "POST", "/v1/device/events", body, now)
	if err != nil {
		t.Fatalf("Headers failed: %v", err)
	}

	if headers[HeaderDevice] != creds.DeviceID {
		t.Errorf("device header = %q, want %q", headers[HeaderDevice], creds.DeviceID)
	}
	if headers[HeaderTimestamp] != "1760000000" {
		t.Errorf("timestamp header = %q, want 1760000000", headers[HeaderTimestamp])
	}
	if err := ValidateNonce(headers[HeaderNonce]); err != nil {
		t.Errorf("nonce header is malformed: %v", err)
	}
	if err := ValidateSignature(headers[HeaderSignature]); err != nil {
		t.Errorf("signature header is malformed: %v", err)
	}

	// The signature must be over the nonce that is actually sent, not a freshly generated one.
	expected := Sign(creds.Secret, Request{
		Method:    "POST",
		Path:      "/v1/device/events",
		Timestamp: now.Unix(),
		Nonce:     headers[HeaderNonce],
		Body:      body,
	})
	if headers[HeaderSignature] != expected {
		t.Error("the signature header does not correspond to the nonce header that was sent")
	}

	// The secret must not leak into any header value.
	for name, value := range headers {
		if strings.Contains(value, creds.Secret) {
			t.Errorf("header %s contains the device secret", name)
		}
	}
}

func TestHeadersUsesAFreshNonceEachCall(t *testing.T) {
	creds := Credentials{DeviceID: "d", Secret: "s"}
	now := time.Unix(1760000000, 0)

	first, err := Headers(creds, "GET", "/v1/device/config", nil, now)
	if err != nil {
		t.Fatalf("Headers failed: %v", err)
	}
	second, err := Headers(creds, "GET", "/v1/device/config", nil, now)
	if err != nil {
		t.Fatalf("Headers failed: %v", err)
	}

	// Reusing a nonce means the second request is rejected as a replay — which is exactly
	// what would happen to a retry if the nonce were cached with the request.
	if first[HeaderNonce] == second[HeaderNonce] {
		t.Error("two calls produced the same nonce; the server would reject the second as a replay")
	}
	if first[HeaderSignature] == second[HeaderSignature] {
		t.Error("two calls produced the same signature despite different nonces")
	}
}

func TestValidateNonce(t *testing.T) {
	valid := "0123456789abcdef0123456789abcdef"
	if err := ValidateNonce(valid); err != nil {
		t.Errorf("valid nonce rejected: %v", err)
	}

	for name, nonce := range map[string]string{
		"too short":  "abc",
		"too long":   valid + "00",
		"not hex":    strings.Repeat("z", 32),
		"upper case": strings.ToUpper(valid),
		"empty":      "",
	} {
		if err := ValidateNonce(nonce); err == nil {
			t.Errorf("%s nonce was accepted", name)
		}
	}
}

func TestValidateSignature(t *testing.T) {
	valid := strings.Repeat("ab", 32)
	if err := ValidateSignature(valid); err != nil {
		t.Errorf("valid signature rejected: %v", err)
	}

	for name, sig := range map[string]string{
		"too short":  "abcd",
		"too long":   valid + "cd",
		"not hex":    strings.Repeat("g", 64),
		"upper case": strings.ToUpper(valid),
		"empty":      "",
	} {
		if err := ValidateSignature(sig); err == nil {
			t.Errorf("%s signature was accepted", name)
		}
	}
}

